// apartmentLayout.js — 鷹匠マンション実寸3Dレイアウト定義
// SVG間取り図の座標をメートル単位の3D座標へ変換する。
// 座標系: x=東(右), y=上, z=南(手前/バルコニー側)。原点=アパート中心。
//
// スケール根拠:
//   I型 専有面積 68.26㎡, SVG部屋ゾーン 184×236 = 43,424 SVG²
//   scale = sqrt(68.26 / 43424) ≈ 0.040 m/SVGunit
//   → 3D床面積: 7.36m × 9.44m ≈ 69.5㎡ (実寸に一致)
//
//   H型 専有面積 42.12㎡, SVG部屋ゾーン 172×208 = 35,776 SVG²
//   scale = sqrt(42.12 / 35776) ≈ 0.034 m/SVGunit
//   → 3D床面積: 5.85m × 7.07m ≈ 41.4㎡ (実寸に一致)

function derive(rooms, sx, sz, cx, cz) {
  return rooms.map(r => ({
    ...r,
    x: (r.svg.x + r.svg.w / 2 - cx) * sx,
    z: (r.svg.y + r.svg.h / 2 - cz) * sz,
    w: r.svg.w * sx,
    d: r.svg.h * sz,
  }))
}

